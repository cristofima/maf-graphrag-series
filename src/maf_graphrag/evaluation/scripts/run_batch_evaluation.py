"""Run batch evaluation using Microsoft Foundry evaluators.

This script consumes ``eval_data.jsonl`` generated by
``generate_eval_data.py`` and evaluates the captured conversations with
Microsoft Agent Framework's Foundry-native evaluation pipeline. Custom
GraphRAG evaluators (entity accuracy and relationship validity) are
executed locally for additional signal. The resulting metrics are written
to ``evaluation_results.json`` and summarized in a Markdown report.

Usage::

    uv run python -m maf_graphrag.evaluation.scripts.run_batch_evaluation
    uv run python -m maf_graphrag.evaluation.scripts.run_batch_evaluation --foundry
"""

from __future__ import annotations

import argparse
import asyncio
import contextlib
import json
import logging
import sys
from collections import defaultdict
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any

from dotenv import load_dotenv

if TYPE_CHECKING:
    from agent_framework import EvalItem
    from agent_framework._evaluation import EvalResults

    from maf_graphrag.evaluation.config import EvalConfig

load_dotenv()

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

logger = logging.getLogger(__name__)

DATASETS_DIR = Path(__file__).resolve().parent.parent / "datasets"
EVAL_DATA_PATH = DATASETS_DIR / "eval_data.jsonl"
RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"


def _resolve_cli_data_path(path_value: str | Path) -> Path:
    """Resolve a CLI-provided dataset path inside the datasets directory."""
    candidate = Path(path_value).expanduser()
    if not candidate.is_absolute():
        candidate = DATASETS_DIR / candidate

    resolved_candidate = candidate.resolve(strict=False)
    resolved_root = DATASETS_DIR.resolve()

    try:
        resolved_candidate.relative_to(resolved_root)
    except ValueError as exc:
        raise ValueError(f"Evaluation data path must stay within {resolved_root}: {resolved_candidate}") from exc

    if resolved_candidate.suffix.lower() != ".jsonl":
        raise ValueError(f"Evaluation data path must point to a .jsonl file: {resolved_candidate}")

    return resolved_candidate


def run_batch_evaluation(
    data_path: str | Path = EVAL_DATA_PATH,
    output_dir: str | Path = RESULTS_DIR,
    *,
    use_foundry: bool = False,
    include_custom: bool = True,
    local_only: bool = False,
) -> dict[str, object]:
    """Run batch evaluation and return aggregated metrics."""
    from maf_graphrag.evaluation.config import EvalConfig

    data_path = _resolve_cli_data_path(data_path)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if not data_path.exists():
        raise FileNotFoundError(f"Evaluation data not found: {data_path}. Run generate_eval_data.py first.")

    if use_foundry:
        logger.info("--foundry flag is deprecated; Foundry-based evaluation now runs by default.")

    config = EvalConfig.from_env()
    items, rows_for_custom = _load_eval_items(data_path)

    eval_name = f"graphrag-batch-{datetime.now(UTC).strftime('%Y%m%d-%H%M%S')}"

    if local_only:
        logger.info("Running local-only evaluation (no Foundry calls) on %s", data_path)
        eval_result = asyncio.run(_evaluate_locally(items, eval_name))
    else:
        logger.info("Running Foundry evaluation on %s", data_path)
        eval_result = asyncio.run(_evaluate_with_foundry(items, config, eval_name))

    metrics: dict[str, float] = {}
    metrics.update(_collect_foundry_metrics(eval_result))

    foundry_summary = _summarize_foundry_run(eval_result)
    if not local_only and config.azure_ai_project:
        foundry_summary.setdefault("project_endpoint", str(config.azure_ai_project))
        foundry_summary.setdefault("auth_mode", config.foundry_auth_mode)

    if include_custom:
        metrics.update(_run_custom_evaluators(rows_for_custom, config))

    result: dict[str, object] = {
        "metrics": metrics,
        "foundry": foundry_summary,
    }

    if eval_result.report_url:
        result["studio_url"] = eval_result.report_url

    route_summary = _compute_route_summary(data_path)
    if route_summary is not None:
        result["route_summary"] = route_summary

    (output_dir / "evaluation_results.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    _write_report(result, output_dir / "evaluation_report.md")

    return result


def _write_report(result: dict[str, object], output_path: Path) -> None:
    """Write a Markdown evaluation report."""
    metrics = result.get("metrics") if isinstance(result.get("metrics"), Mapping) else {}
    studio_url = result.get("studio_url", "")
    route_summary = result.get("route_summary")

    lines = [
        "# Evaluation Report",
        "",
        "## Summary Metrics",
        "",
        "| Evaluator | Score |",
        "|-----------|-------|",
    ]

    for name, value in sorted(metrics.items()):
        lines.append(f"| {name} | {value} |")

    lines.append("")
    lines.extend(_build_route_summary_lines(route_summary))

    if studio_url:
        lines.append("## Azure AI Foundry Dashboard")
        lines.append("")
        lines.append(f"[View detailed results]({studio_url})")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by `maf_graphrag.evaluation.scripts.run_batch_evaluation`*")

    output_path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Report written to %s", output_path)


# Agent Framework's Content.from_dict() only recognizes "function_call"/"function_result"
# as content types; the OpenAI-style "tool_call"/"tool_result" chunks produced by
# generate_eval_data.py pass through unrecognized, which makes AgentEvalConverter treat
# the message as plain text and drop tool_call_id entirely (Foundry then rejects the
# resulting 'tool' message for missing tool_call_id).
_CONTENT_TYPE_ALIASES: dict[str, str] = {
    "tool_call": "function_call",
    "tool_result": "function_result",
}


def _normalize_message_payload(message_data: Mapping[str, object]) -> dict[str, object]:
    """Sanitize serialized messages so Agent Framework accepts tool call metadata."""

    normalized: dict[str, object] = dict(message_data)

    tool_call_id = normalized.pop("tool_call_id", None)

    raw_contents = normalized.get("contents")
    if isinstance(raw_contents, Sequence):
        coerced_contents: list[object] = []
        for chunk in raw_contents:
            if not isinstance(chunk, Mapping):
                coerced_contents.append(chunk)
                continue

            chunk_dict: dict[str, object] = dict(chunk)

            chunk_call_id = chunk_dict.pop("tool_call_id", None) or tool_call_id
            if chunk_call_id is not None:
                chunk_dict.setdefault("call_id", str(chunk_call_id))

            if "tool_result" in chunk_dict:
                chunk_dict.setdefault("result", chunk_dict.pop("tool_result"))

            if "name" in chunk_dict and "tool_name" not in chunk_dict:
                chunk_dict["tool_name"] = chunk_dict["name"]

            chunk_type = chunk_dict.get("type")
            if isinstance(chunk_type, str) and chunk_type in _CONTENT_TYPE_ALIASES:
                chunk_dict["type"] = _CONTENT_TYPE_ALIASES[chunk_type]

            coerced_contents.append(chunk_dict)

        normalized["contents"] = coerced_contents

    return normalized


def _load_eval_items(data_path: Path) -> tuple[list[EvalItem], list[dict[str, object]]]:
    """Load evaluation records and convert them to ``EvalItem`` objects."""
    from agent_framework import EvalItem, ExpectedToolCall, FunctionTool
    from agent_framework._types import Message

    items: list[EvalItem] = []
    rows_for_custom: list[dict[str, object]] = []

    with data_path.open(encoding="utf-8") as file_handle:
        for line in file_handle:
            stripped = line.strip()
            if not stripped:
                continue

            entry = json.loads(stripped)
            query = str(entry.get("query", "")).strip()
            if not query:
                continue

            conversation_payload = entry.get("conversation")
            if not isinstance(conversation_payload, list):
                raw_response = entry.get("response")
                if isinstance(raw_response, list):
                    conversation_payload = raw_response
                elif isinstance(raw_response, str) and raw_response.strip():
                    # Simple string query/response rows (e.g. eval_router_data.jsonl) are a
                    # documented Foundry dataset shape; wrap as a single assistant turn so
                    # EvalItem still gets a non-empty conversation instead of being skipped.
                    conversation_payload = [{"role": "assistant", "contents": [{"type": "text", "text": raw_response}]}]
                else:
                    conversation_payload = []

            conversation: list[Message] = []
            for message_data in conversation_payload:
                if not isinstance(message_data, Mapping):
                    continue

                normalized_message = _normalize_message_payload(message_data)
                try:
                    conversation.append(Message.from_dict(normalized_message))
                except Exception as exc:  # pragma: no cover - defensive guard
                    logger.debug("Skipping malformed conversation message: %s", exc, exc_info=exc)

            if not conversation:
                logger.warning("Skipping evaluation row without conversation messages for query '%s'", query)
                continue

            if not any(
                getattr(message, "role", "") == "user" and getattr(message, "text", "").strip()
                for message in conversation
            ):
                conversation.insert(
                    0,
                    Message.from_dict(
                        {
                            "role": "user",
                            "contents": [
                                {
                                    "type": "text",
                                    "text": query,
                                }
                            ],
                        }
                    ),
                )

            tool_defs_raw = entry.get("tool_definitions") if isinstance(entry.get("tool_definitions"), list) else []
            tools = []
            for tool_def in tool_defs_raw:
                if isinstance(tool_def, dict):
                    try:
                        tool_obj = FunctionTool.from_dict(dict(tool_def))
                    except Exception as exc:  # pragma: no cover - defensive guard
                        logger.debug("Skipping malformed tool definition: %s", exc)
                    else:
                        # Older serialized tool specs set ``parameters`` directly on the
                        # instance, which masks the callable ``parameters()`` helper.
                        if isinstance(getattr(tool_obj, "parameters", None), dict):
                            cached_schema = tool_obj.parameters
                            tool_obj._cached_parameters = cached_schema
                            with contextlib.suppress(AttributeError):
                                delattr(tool_obj, "parameters")
                        tools.append(tool_obj)

            response_text = entry.get("response_text") if isinstance(entry.get("response_text"), str) else None
            if not response_text:
                response_text = _extract_response_text(conversation_payload)

            ground_truth = str(entry.get("ground_truth", "")).strip() or None

            expected_tool_calls: list[ExpectedToolCall] | None = None
            raw_expected = entry.get("expected_tool_calls")
            if isinstance(raw_expected, list):
                collected_calls: list[ExpectedToolCall] = []
                for call in raw_expected:
                    if isinstance(call, dict):
                        name = call.get("name")
                        if not isinstance(name, str) or not name:
                            continue
                        arguments = call.get("arguments")
                        arguments_payload = dict(arguments) if isinstance(arguments, Mapping) else None
                        collected_calls.append(ExpectedToolCall(name=name, arguments=arguments_payload))
                    elif isinstance(call, str) and call:
                        collected_calls.append(ExpectedToolCall(name=call))
                expected_tool_calls = collected_calls or None

            if expected_tool_calls is None and isinstance(entry.get("expected_tools"), list):
                expected_tool_calls = [
                    ExpectedToolCall(name=str(tool_name))
                    for tool_name in entry["expected_tools"]
                    if isinstance(tool_name, str) and tool_name.strip()
                ] or None

            if expected_tool_calls is None and isinstance(entry.get("tool_calls"), list):
                derived_calls: list[ExpectedToolCall] = []
                for call in entry["tool_calls"]:
                    if not isinstance(call, dict):
                        continue
                    name = call.get("name")
                    if not isinstance(name, str) or not name.strip():
                        continue
                    arguments = call.get("arguments")
                    arguments_payload = dict(arguments) if isinstance(arguments, Mapping) else None
                    derived_calls.append(ExpectedToolCall(name=name.strip(), arguments=arguments_payload))
                expected_tool_calls = derived_calls or None

            if expected_tool_calls is None:
                derived_calls: list[ExpectedToolCall] = []
                for message_data in conversation_payload:
                    if not isinstance(message_data, Mapping):
                        continue

                    contents = message_data.get("contents")
                    if not isinstance(contents, list):
                        continue

                    for chunk in contents:
                        if not isinstance(chunk, Mapping):
                            continue
                        if chunk.get("type") != "tool_call":
                            continue

                        name = chunk.get("name")
                        if not isinstance(name, str) or not name.strip():
                            continue
                        arguments = chunk.get("arguments")
                        arguments_payload = dict(arguments) if isinstance(arguments, Mapping) else None
                        derived_calls.append(ExpectedToolCall(name=name.strip(), arguments=arguments_payload))

                expected_tool_calls = derived_calls or None

            init_kwargs: dict[str, object] = {
                "conversation": conversation,
                "tools": tools or None,
                "expected_output": ground_truth,
            }
            if expected_tool_calls:
                init_kwargs["expected_tool_calls"] = expected_tool_calls
            items.append(EvalItem(**init_kwargs))

            rows_for_custom.append(
                {
                    "query": query,
                    "response_text": response_text or "",
                    "response": response_text or "",
                    "ground_truth": ground_truth or "",
                    "tool_definitions": tool_defs_raw,
                }
            )

    if not items:
        raise ValueError(f"No evaluation rows were loaded from {data_path}")

    return items, rows_for_custom


# FoundryEvals defaults to relevance/coherence/task_adherence and only auto-adds
# tool_call_accuracy for tool-aware items. All GraphRAG tools are plain Function Tools
# (fully supported by agent evaluators, per the Foundry agent-evaluators guidance), so the
# remaining process evaluators are safe to request explicitly; FoundryEvals drops them
# automatically for items without tool definitions.
_FOUNDRY_EVALUATORS: list[str] = [
    "relevance",
    "coherence",
    "task_adherence",
    "tool_call_accuracy",
    "tool_selection",
    "tool_input_accuracy",
    "tool_output_utilization",
    "tool_call_success",
]


async def _evaluate_with_foundry(items: Sequence[EvalItem], config: EvalConfig, eval_name: str) -> EvalResults:
    """Evaluate items with Microsoft Foundry."""
    from agent_framework_foundry import FoundryChatClient, FoundryEvals

    evaluator_kwargs: dict[str, Any] = {
        "model": config.eval_chat_deployment,
        "evaluators": _FOUNDRY_EVALUATORS,
        # 8 evaluators per item take longer than FoundryEvals' 180s default poll timeout;
        # the run itself keeps executing in Foundry, but the client gives up and reports
        # status="timeout" with empty metrics if we don't raise the local poll budget.
        "timeout": 600.0,
    }
    if config.azure_ai_project:
        evaluator_kwargs["client"] = FoundryChatClient(**config.build_foundry_client_kwargs())

    evaluator = FoundryEvals(**evaluator_kwargs)
    return await evaluator.evaluate(items, eval_name=eval_name)


async def _evaluate_locally(items: Sequence[EvalItem], eval_name: str) -> EvalResults:
    """Evaluate items with Agent Framework's native ``LocalEvaluator`` (no Azure/Foundry calls).

    Used for cost-sensitive profiles (e.g. the PR merge gate) where ``publish_foundry`` is
    false or Foundry credentials are unavailable. Checks are limited to tool-call correctness
    since that is derivable purely from the loaded conversation/``expected_tool_calls`` data.
    """
    from agent_framework import LocalEvaluator, tool_call_args_match, tool_calls_present

    evaluator = LocalEvaluator(tool_calls_present, tool_call_args_match)
    return await evaluator.evaluate(items, eval_name=eval_name)


def _collect_foundry_metrics(results: EvalResults) -> dict[str, float]:
    """Summarize Foundry evaluator scores into average metrics."""
    aggregates: dict[str, list[float]] = defaultdict(list)

    for item in results.items:
        for score in item.scores:
            if isinstance(score.score, (int, float)):
                aggregates[score.name].append(float(score.score))

    metrics: dict[str, float] = {}
    for name, values in aggregates.items():
        if values:
            metrics[name] = round(sum(values) / len(values), 4)

    if not metrics and results.per_evaluator:
        for name, counts in results.per_evaluator.items():
            passed = counts.get("passed", 0)
            failed = counts.get("failed", 0)
            total = passed + failed
            if total:
                metrics[name] = round(passed / total, 4)

    return metrics


def _run_custom_evaluators(rows: Sequence[dict[str, object]], config: EvalConfig) -> dict[str, float]:
    """Execute custom GraphRAG evaluators and aggregate their scores."""
    evaluators: list[tuple[str, object]] = []

    entities_path = _resolve_parquet_path(Path(config.entities_parquet_path), fallback_name="entities.parquet")
    relationships_path = _resolve_parquet_path(
        Path(config.relationships_parquet_path),
        fallback_name="relationships.parquet",
    )

    if entities_path.exists():
        try:
            from maf_graphrag.evaluation.evaluators.entity_accuracy import EntityAccuracyEvaluator

            evaluators.append(("entity_accuracy", EntityAccuracyEvaluator(str(entities_path))))
        except Exception as exc:  # pragma: no cover - depends on local parquet shape
            logger.warning("Skipping EntityAccuracyEvaluator due to initialization error: %s", exc)

    if relationships_path.exists() and entities_path.exists():
        try:
            from maf_graphrag.evaluation.evaluators.relationship_validity import RelationshipValidityEvaluator

            evaluators.append(
                (
                    "relationship_validity",
                    RelationshipValidityEvaluator(str(relationships_path), str(entities_path)),
                )
            )
        except Exception as exc:  # pragma: no cover - depends on local parquet shape
            logger.warning("Skipping RelationshipValidityEvaluator due to initialization error: %s", exc)

    if not evaluators:
        return {}

    aggregates: dict[str, list[float]] = defaultdict(list)

    for row in rows:
        response_text = row.get("response_text", "")
        for metric_name, evaluator in evaluators:
            try:
                payload = evaluator(response=response_text)
            except Exception as exc:  # pragma: no cover - defensive guard
                logger.warning("Custom evaluator '%s' failed: %s", metric_name, exc)
                continue

            score = payload.get(metric_name)
            if isinstance(score, (int, float)):
                aggregates[metric_name].append(float(score))

    metrics: dict[str, float] = {}
    for name, values in aggregates.items():
        if values:
            metrics[name] = round(sum(values) / len(values), 4)

    return metrics


def _summarize_foundry_run(result: EvalResults) -> dict[str, object]:
    """Return a simplified summary of the Foundry evaluation run."""
    summary: dict[str, object] = {
        "provider": result.provider,
        "status": result.status,
        "passed": result.passed,
        "failed": result.failed,
        "total": result.total,
        "per_evaluator": result.per_evaluator,
    }
    if result.eval_id:
        summary["eval_id"] = result.eval_id
    if result.run_id:
        summary["run_id"] = result.run_id
    if result.report_url:
        summary["report_url"] = result.report_url
    if result.error:
        summary["error"] = result.error
    return summary


def _extract_response_text(response: object) -> str:
    """Extract assistant text from structured response payloads."""
    if isinstance(response, str):
        return response

    if isinstance(response, dict):
        content = response.get("contents")
        if content is None:
            content = response.get("content", "")
        return _extract_text_from_content(content)

    if isinstance(response, list):
        assistant_text = _extract_last_assistant_text(response)
        if assistant_text:
            return assistant_text

        try:
            return json.dumps(response, ensure_ascii=False)
        except TypeError:
            return str(response)

    return str(response)


def _extract_text_from_content(content: object) -> str:
    """Extract text from OpenAI-style message content."""
    if isinstance(content, str):
        return content

    if not isinstance(content, list):
        return str(content)

    chunks: list[str] = []
    for item in content:
        if isinstance(item, str):
            chunks.append(item)
            continue

        if isinstance(item, dict):
            if item.get("type") in {"text", "input_text", "output_text"} and isinstance(item.get("text"), str):
                chunks.append(item["text"])
                continue

            if isinstance(item.get("tool_result"), str):
                chunks.append(item["tool_result"])

    return "\n".join(chunk for chunk in chunks if chunk).strip()


def _extract_last_assistant_text(messages: list[object]) -> str:
    """Extract the most recent assistant text from message history."""
    for message in reversed(messages):
        if not isinstance(message, dict):
            continue

        if str(message.get("role", "")).lower() != "assistant":
            continue

        content = message.get("contents")
        if content is None:
            content = message.get("content", "")

        text = _extract_text_from_content(content)
        if text:
            return text

    return ""


def _resolve_parquet_path(preferred_path: Path, *, fallback_name: str) -> Path:
    """Resolve graph parquet file path with a backward-compatible fallback."""
    if preferred_path.exists():
        return preferred_path

    fallback_path = preferred_path.parent / fallback_name
    if fallback_path.exists():
        logger.info("Using fallback parquet path: %s", fallback_path)
        return fallback_path

    logger.warning("Parquet path not found: %s", preferred_path)
    return preferred_path


def _compute_route_summary(data_path: Path) -> dict[str, object] | None:
    """Compute router route-accuracy summary when route fields are present."""
    total_cases = 0
    decided_cases = 0
    matched_cases = 0
    flexible_cases = 0
    flexible_matched_cases = 0
    by_expected_route: dict[str, dict[str, int]] = {}
    saw_route_fields = False

    with data_path.open(encoding="utf-8") as file_handle:
        for line in file_handle:
            row = _coerce_route_summary_row(line)
            if row is None:
                continue

            if {"route_match", "expected_routed_workflow", "accepted_routed_workflows"} & row.keys():
                saw_route_fields = True

            route_match = row.get("route_match")
            expected_route = row.get("expected_routed_workflow")
            accepted_routes = row.get("accepted_routed_workflows")

            total_cases += 1
            (
                total_cases,
                decided_cases,
                matched_cases,
                flexible_cases,
                flexible_matched_cases,
            ) = _update_route_summary_counts(
                route_match=route_match,
                accepted_routes=accepted_routes,
                expected_route=expected_route,
                by_expected_route=by_expected_route,
                counts=(total_cases, decided_cases, matched_cases, flexible_cases, flexible_matched_cases),
            )

    if total_cases == 0 or not saw_route_fields:
        return None

    summary: dict[str, object] = {
        "total_cases": total_cases,
        "decided_cases": decided_cases,
        "matched_cases": matched_cases,
        "route_accuracy": (matched_cases / decided_cases) if decided_cases else None,
        "flexible_cases": flexible_cases,
        "flexible_matched_cases": flexible_matched_cases,
        "flexible_accuracy": (flexible_matched_cases / flexible_cases) if flexible_cases else None,
    }

    if by_expected_route:
        by_route: dict[str, dict[str, object]] = {}
        for route, stats in by_expected_route.items():
            cases = stats["cases"]
            matched = stats["matched"]
            by_route[route] = {
                "cases": cases,
                "matched": matched,
                "accuracy": (matched / cases) if cases else None,
            }
        summary["by_expected_route"] = by_route

    return summary


def _coerce_route_summary_row(line: str) -> dict[str, object] | None:
    """Parse a single JSONL route-summary row when it contains the expected fields."""
    stripped = line.strip()
    if not stripped:
        return None

    row = json.loads(stripped)
    return row if isinstance(row, dict) else None


def _update_route_summary_counts(
    *,
    route_match: object,
    accepted_routes: object,
    expected_route: object,
    by_expected_route: dict[str, dict[str, int]],
    counts: tuple[int, int, int, int, int],
) -> tuple[int, int, int, int, int]:
    """Mutate counters for a single route-summary row."""
    total_cases, decided_cases, matched_cases, flexible_cases, flexible_matched_cases = counts
    if isinstance(route_match, bool):
        decided_cases += 1
        if route_match:
            matched_cases += 1

    if isinstance(accepted_routes, list):
        normalized_accepted_routes = [value for value in accepted_routes if isinstance(value, str) and value.strip()]
        if len(normalized_accepted_routes) > 1:
            flexible_cases += 1
            if route_match is True:
                flexible_matched_cases += 1

    if isinstance(expected_route, str) and expected_route.strip():
        key = expected_route.strip().lower()
        stats = by_expected_route.setdefault(key, {"cases": 0, "matched": 0})
        stats["cases"] += 1
        if route_match is True:
            stats["matched"] += 1

    return total_cases, decided_cases, matched_cases, flexible_cases, flexible_matched_cases


def _build_route_summary_lines(route_summary: object) -> list[str]:
    """Return Markdown lines for a route-summary payload when present."""
    if not isinstance(route_summary, dict):
        return []

    lines = ["## Router Route Accuracy", ""]
    lines.extend(_build_route_accuracy_lines(route_summary))
    lines.extend(_build_expected_route_lines(route_summary.get("by_expected_route")))
    return lines


def _build_route_accuracy_lines(route_summary: Mapping[str, object]) -> list[str]:
    """Return the summary statistics section for route accuracy."""
    lines: list[str] = []
    total_cases = route_summary.get("total_cases")
    decided_cases = route_summary.get("decided_cases")
    matched_cases = route_summary.get("matched_cases")
    route_accuracy = route_summary.get("route_accuracy")
    flexible_cases = route_summary.get("flexible_cases")
    flexible_matched_cases = route_summary.get("flexible_matched_cases")
    flexible_accuracy = route_summary.get("flexible_accuracy")

    lines.append(f"- Total cases: {total_cases}")
    lines.append(f"- Decided cases: {decided_cases}")
    lines.append(f"- Matched routes: {matched_cases}")
    if isinstance(route_accuracy, (int, float)):
        lines.append(f"- Route accuracy: {route_accuracy:.3f} ({route_accuracy * 100:.1f}%)")
    if isinstance(flexible_cases, int):
        lines.append(f"- Flexible cases (multi-valid route): {flexible_cases}")
    if isinstance(flexible_matched_cases, int):
        lines.append(f"- Flexible matched cases: {flexible_matched_cases}")
    if isinstance(flexible_accuracy, (int, float)):
        lines.append(f"- Flexible accuracy: {flexible_accuracy:.3f} ({flexible_accuracy * 100:.1f}%)")
    lines.append("")
    return lines


def _build_expected_route_lines(by_expected: object) -> list[str]:
    """Return the per-route breakdown section when available."""
    if not isinstance(by_expected, Mapping) or not by_expected:
        return []

    lines = ["| Expected Route | Cases | Matched | Accuracy |", "|----------------|-------|---------|----------|"]
    for expected_route, stats in sorted(by_expected.items()):
        if not isinstance(stats, Mapping):
            continue
        cases = stats.get("cases", 0)
        matched = stats.get("matched", 0)
        accuracy = stats.get("accuracy")
        if isinstance(accuracy, (int, float)):
            accuracy_text = f"{accuracy:.3f}"
        else:
            accuracy_text = "n/a"
        lines.append(f"| {expected_route} | {cases} | {matched} | {accuracy_text} |")
    lines.append("")
    return lines


